import {
  BadRequestException,
  ConflictException,
  Injectable,
  NotFoundException,
} from '@nestjs/common';
import { InjectDataSource, InjectRepository } from '@nestjs/typeorm';
import { DataSource, Repository } from 'typeorm';
import { isPgError, PG_UNIQUE_VIOLATION } from '../common/db-errors';
import { HallsService } from '../halls/halls.service';
import { ShowingsService } from '../showings/showings.service';
import {
  BookingResponseDto,
  SeatAvailabilityDto,
} from './dto/booking-response.dto';
import { CreateBookingDto, SeatDto } from './dto/create-booking.dto';
import { BookingSeat } from './entities/booking-seat.entity';
import { Booking } from './entities/booking.entity';

/** Largest value of a PostgreSQL `integer` column (bookings.total_price). */
const MAX_INT4 = 2_147_483_647;

const bySeat = (a: SeatDto, b: SeatDto): number =>
  a.row - b.row || a.seat - b.seat;

const seatLabel = (seat: SeatDto): string =>
  `(row ${seat.row}, seat ${seat.seat})`;

@Injectable()
export class BookingsService {
  constructor(
    @InjectRepository(Booking)
    private readonly bookingsRepository: Repository<Booking>,
    @InjectRepository(BookingSeat)
    private readonly bookingSeatsRepository: Repository<BookingSeat>,
    @InjectDataSource()
    private readonly dataSource: DataSource,
    private readonly showingsService: ShowingsService,
    private readonly hallsService: HallsService,
  ) {}

  /**
   * Books all seats of the request or none of them.
   *
   * The booking row and every seat row are written in ONE transaction. The
   * unique index on booking_seats (showing_id, row, seat) is what stops a seat
   * from being sold twice: if any seat is taken, the insert fails, TypeORM
   * rolls the transaction back, and neither the booking nor any seat of this
   * request stays in the database. This holds for two requests that arrive at
   * the same moment too, because the index is checked by the database, not by
   * this code.
   *
   * The try/catch is around `transaction()` and not inside the callback: the
   * error has to reach TypeORM so that it rolls back.
   */
  async create(
    showingId: string,
    dto: CreateBookingDto,
  ): Promise<BookingResponseDto> {
    const showing = await this.showingsService.findEntity(showingId);
    const hall = showing.hall;

    // Layout of the hall: every seat must exist. Needs no stored state of the
    // showing, so it is checked before the transaction opens.
    for (const { row, seat } of dto.seats) {
      if (row > hall.rows || seat > hall.seatsPerRow) {
        throw new BadRequestException(
          `Seat (row ${row}, seat ${seat}) does not exist in hall "${hall.name}": ${hall.rows} rows, ${hall.seatsPerRow} seats per row`,
        );
      }
    }

    const totalPrice = showing.price * dto.seats.length;
    if (totalPrice > MAX_INT4) {
      throw new BadRequestException(
        'Total price of the booking is too large: choose fewer seats',
      );
    }

    try {
      return await this.dataSource.transaction(async (manager) => {
        // booking.id is generated by the database on insert, so the seats are
        // built after this save.
        const booking = manager.create(Booking, { showingId, totalPrice });
        await manager.save(booking);

        const seats = dto.seats.map(({ row, seat }) =>
          manager.create(BookingSeat, {
            bookingId: booking.id,
            showingId,
            row,
            seat,
          }),
        );
        await manager.save(seats);

        return {
          id: booking.id,
          showingId,
          seats: dto.seats
            .map(({ row, seat }) => ({ row, seat }))
            .sort(bySeat),
          totalPrice,
        };
      });
    } catch (error) {
      if (isPgError(error, PG_UNIQUE_VIOLATION)) {
        // Only our own text goes into the answer, never the database message.
        throw new ConflictException(
          await this.takenSeatsMessage(showingId, dto.seats),
        );
      }
      throw error;
    }
  }

  async findAll(): Promise<BookingResponseDto[]> {
    const bookings = await this.bookingsRepository.find({
      relations: { seats: true },
      order: { createdAt: 'ASC', id: 'ASC' },
    });
    return bookings.map((booking) => this.toResponse(booking));
  }

  async findByShowing(showingId: string): Promise<BookingResponseDto[]> {
    await this.showingsService.findEntity(showingId); // 404 if unknown
    const bookings = await this.bookingsRepository.find({
      where: { showingId },
      relations: { seats: true },
      order: { createdAt: 'ASC', id: 'ASC' },
    });
    return bookings.map((booking) => this.toResponse(booking));
  }

  /** Seat map of a showing: the layout of its hall plus who holds what. */
  async getSeatMap(showingId: string): Promise<SeatAvailabilityDto[]> {
    const showing = await this.showingsService.findEntity(showingId);
    const taken = await this.bookingSeatsRepository.find({
      where: { showingId },
      select: { row: true, seat: true },
    });
    const takenKeys = new Set(taken.map((seat) => `${seat.row}:${seat.seat}`));
    return this.hallsService.buildSeats(showing.hall).map((seat) => ({
      row: seat.row,
      seat: seat.seat,
      isBooked: takenKeys.has(`${seat.row}:${seat.seat}`),
    }));
  }

  /**
   * Cancels a booking. Its seats are removed by the database itself:
   * booking_seats.booking_id is ON DELETE CASCADE, so no seat is deleted here.
   */
  async remove(id: string): Promise<void> {
    const result = await this.bookingsRepository.delete(id);
    if (!result.affected) {
      throw new NotFoundException(`Booking with id ${id} not found`);
    }
  }

  /** Which of the requested seats are taken, for the 409 text. */
  private async takenSeatsMessage(
    showingId: string,
    requested: SeatDto[],
  ): Promise<string> {
    const taken = await this.bookingSeatsRepository.find({
      where: requested.map(({ row, seat }) => ({ showingId, row, seat })),
      select: { row: true, seat: true },
    });
    if (taken.length === 0) {
      return 'One or more of the requested seats are already booked on this showing';
    }
    return `Seats already booked on this showing: ${taken
      .sort(bySeat)
      .map(seatLabel)
      .join(', ')}`;
  }

  private toResponse(booking: Booking): BookingResponseDto {
    return {
      id: booking.id,
      showingId: booking.showingId,
      seats: booking.seats
        .map(({ row, seat }) => ({ row, seat }))
        .sort(bySeat),
      totalPrice: booking.totalPrice,
    };
  }
}
